"""Shared MLflow setup: local tracking on a sqlite backend, artifacts in
./mlartifacts/ (both gitignored - never committed, regenerated by
rerunning the training scripts).
"""

import json
import subprocess
from pathlib import Path

import mlflow
import mlflow.pyfunc

TRACKING_URI = "sqlite:///mlflow.db"
ARTIFACT_LOCATION = "./mlartifacts"
EXPERIMENT_NAME = "credit-default-risk-engine"


def setup_mlflow() -> None:
    mlflow.set_tracking_uri(TRACKING_URI)
    experiment = mlflow.get_experiment_by_name(EXPERIMENT_NAME)
    if experiment is None:
        mlflow.create_experiment(EXPERIMENT_NAME, artifact_location=ARTIFACT_LOCATION)
    mlflow.set_experiment(EXPERIMENT_NAME)


def git_hash() -> str:
    return subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()


def raw_data_sha256() -> str:
    with open("reports/metrics/raw_data_profile.json") as f:
        profile = json.load(f)
    return profile["raw_file_sha256"]


def log_common_context() -> None:
    """Call inside an active run: logs the raw data hash and git hash every
    run should carry, regardless of which script is logging."""
    mlflow.log_param("git_hash", git_hash())
    mlflow.log_param("raw_data_sha256", raw_data_sha256())


def log_file_if_exists(path: str) -> None:
    if Path(path).exists():
        mlflow.log_artifact(path)


CATEGORICAL_COLUMNS = ["home_ownership", "purpose", "verification_status"]


class LightGBMChampionModel(mlflow.pyfunc.PythonModel):
    """LightGBM booster + Platt calibrator, chained as one deployable unit.
    predict() takes a plain DataFrame (string dtype for categoricals - NOT
    pandas 'category', which MLflow's schema enforcement cannot serialize)
    and returns the calibrated PD, matching score_lightgbm() exactly."""

    def load_context(self, context):
        import joblib

        self.booster = joblib.load(context.artifacts["booster"])
        self.calibrator = joblib.load(context.artifacts["calibrator"])
        with open(context.artifacts["features"]) as f:
            self.features = json.load(f)

    def predict(self, context, model_input, params=None):
        from src.models.gbm import logit

        df = model_input.copy()
        for col in CATEGORICAL_COLUMNS:
            if col in df.columns:
                df[col] = df[col].astype("category")
        raw_pred = self.booster.predict(df[self.features], num_iteration=self.booster.best_iteration)
        return self.calibrator.predict_proba(logit(raw_pred).reshape(-1, 1))[:, 1]
